// skills_collect.go — the box SKILL aggregator feeding the ai.opencharly.skill OCI label.
// A skill is a first-class `skill:` KIND entity (spec.Skill), co-located as a sibling top-level
// node in its owning candy's charly.yml and threaded into spec.Config.Skills (the raw
// uf.PluginKinds["skill"] map, mirroring the Config.Sidecar precedent). CollectSkills is a PURE
// walk producing the []spec.LabelSkillEntry the label carries — an image is SELF-DESCRIBING: its
// composed candies' skill definitions are readable directly via `charly box labels` /
// `charly deploy from-box`, with no external fetch (superseding the vestigial ai.opencharly.skill
// doc-pointer URL).
//
// THE PROSE HALF COMES FROM THE FILE, NOT THE NODE. A skill's body (description/content/
// references) lives in the repository that owns it — `<candy source dir>/<tree>/<name>/SKILL.md`,
// `<tree>` being the Agent-Skills location (see skillTree) and `<name>` the skill id (spec#247).
// The node keeps only the ROUTING metadata (family/owner/triggers/category). This collector reads
// that file through candywalk.ReadSkillFile — the ONE reader the marketplace generator also uses
// — so an image's label keeps carrying the skill WHOLE after a repo has moved its prose out. A
// node that still carries an in-line `content:` and has no file is the transitional form and is
// projected exactly as authored; the generator owns the stricter rule (a node whose in-line body
// DISAGREES with its file is an authoring error there, and such a repo cannot land a corpus).
//
// Ownership: a skill's `owner` field names the candy that owns it. Only skills owned by a candy
// IN the composed chain (BoxCandyChain) ride the image's label — union-of-composed-only, which
// bounds the label size. Concept-candy skills (charly-core, charly-internals, candy/charly-hooks,
// …) are not image layers and never appear in any image's label; they live in the plugins/ corpus
// generated by candy/plugin-marketplace.
//
// Returns nil when the composition declares no skills. An unreadable/malformed file, a body that
// does not decode, and a skill with neither an in-line body nor a file are ERRORS: each of them
// would otherwise silently ship a label entry with its prose missing, which is the exact defect
// this read-back exists to close.
func CollectSkills(cfg *spec.Config, layers map[string]CandyModel, boxName string) ([]spec.LabelSkillEntry, error) {
	allCandyNames, _ := BoxCandyChain(cfg, layers, boxName)
	composed := make(map[string]bool, len(allCandyNames))
	for _, n := range allCandyNames {
		composed[n] = true
	}

	// Decode every authored skill body once; project the ones owned by a composed candy.
	// The map KEY is the node name, which IS the skill id when the node declares no `name:`
	// (spec#247) — the same default the generator applies, and the directory the file lives in.
	byKey := map[string]spec.LabelSkillEntry{}
	var order []string
	for node, raw := range cfg.Skills {
		if len(raw) == 0 {
			continue
		}
		var s spec.Skill
		if err := json.Unmarshal(raw, &s); err != nil {
			return nil, fmt.Errorf("skill %q: decode: %w", node, err)
		}
		if !composed[s.Owner] {
			continue
		}
		entry, err := projectSkill(layers, s, node)
		if err != nil {
			return nil, err
		}
		key := entry.Family + "/" + entry.Name
		if _, dup := byKey[key]; dup {
			continue
		}
		byKey[key] = entry
		order = append(order, key)
	}
	if len(order) == 0 {
		return nil, nil
	}
	sort.Strings(order)
	out := make([]spec.LabelSkillEntry, 0, len(order))
	for _, k := range order {
		out = append(out, byKey[k])
	}
	return out, nil
}

// skillTree is the tree a composed candy's skill files are looked under: the Agent-Skills
// standard location, which is what a candy's `skills:` list means when it declares none.
//
// A candy that declares a NON-default tree is not resolvable from here, and that is a stated
// limit rather than an oversight: the authored `skills:` list lives on #Candy (spec.Candy, read
// by the marketplace generator off the authored entity), and the resolved-project envelope this
// collector walks carries no such field — spec.CandyModel has SourceDir but not Skills, and
// spec.CandyView does not either. So the standard location is used. The failure mode is LOUD, not
// silent: a routing-only skill node under a non-default tree finds no file here and CollectSkills
// errors naming the tree it looked in, rather than shipping an entry with its prose missing.
const skillTree = candywalk.AgentsSkillsDir

// projectSkill maps the authored spec.Skill (the authoring kind shape) onto the wire
// spec.LabelSkillEntry (the label shape) — the authoring → wire projection — with the prose half
// read back from the file the owning repo owns.
func projectSkill(layers map[string]CandyModel, s spec.Skill, node string) (spec.LabelSkillEntry, error) {
	name := s.Name
	if name == "" {
		// The node name IS the id when the node declares none (spec#247's default).
		name = node
	}
	entry := spec.LabelSkillEntry{
		Family:   s.Family,
		Name:     name,
		Owner:    s.Owner,
		Triggers: s.Triggers,
		Category: s.Category,
	}
	for _, r := range s.References {
		entry.References = append(entry.References, spec.LabelSkillReference(r)) // S1016 — convertible field-identical types
	}

	sf, err := readSkillFile(layers, s, name)
	if err != nil {
		return spec.LabelSkillEntry{}, err
	}
	if sf == nil {
		// No file: the transitional in-line form, or no body at all.
		if s.Content == "" {
			return spec.LabelSkillEntry{}, fmt.Errorf(
				"skill %q: no body — the node carries no in-line `content:` and no SKILL.md exists under %s beside the owning candy %q",
				name, skillTree, s.Owner)
		}
		entry.Description = s.Description
		entry.Content = s.Content
		return entry, nil
	}
	entry.Description = sf.Description
	entry.Content = sf.Content
	if len(entry.References) == 0 {
		for _, r := range sf.References {
			entry.References = append(entry.References, spec.LabelSkillReference{Name: r.Stem, Content: r.Content})
		}
	}
	return entry, nil
}

// readSkillFile reads ONE composed skill's prose from the file its repository owns. (nil, nil)
// means "no file here" — the in-line form's case, never an error; every other failure (unreadable
// file, malformed frontmatter, a frontmatter name that disagrees with its directory) is an error,
// because each would otherwise be published under the right name with the wrong prose.
func readSkillFile(layers map[string]CandyModel, s spec.Skill, name string) (*candywalk.SkillFile, error) {
	layer, ok := layers[s.Owner]
	if !ok || layer == nil {
		return nil, nil
	}
	base := layer.GetSourceDir()
	if base == "" {
		return nil, nil
	}
	sf, err := candywalk.ReadSkillFile(filepath.Join(base, skillTree), name)
	if err != nil {
		return nil, fmt.Errorf("skill %q: %w", name, err)
	}
	return sf, nil
}
