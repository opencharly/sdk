package candywalk

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// skillfile_test.go — the `.agents/skills` reader's contract.
//
// Every fixture is byte-shaped the way the marketplace emitter writes it
// (candy/plugin-marketplace `emit_skills.go`: skillFrontmatter + the DO-NOT-EDIT marker +
// TrimSuffix(content, "\n") + "\n"), because the reader's whole job is to be that writer's exact
// inverse: read -> emit must land on the same bytes the corpus carries. The marker is spelled out
// here rather than imported so a change to the emitter's banner text fails THIS test loudly instead
// of silently changing what the reader strips.

const (
	marker = "<!-- GENERATED by `charly marketplace generate` — DO NOT EDIT. Edit the candy's skill:/hook:/marketplace: entities and regenerate. -->"

	// corpusSkill is a skill file as the published CORPUS carries it: frontmatter, marker, body.
	corpusSkill = "---\nname: git-workflow\ndescription: |-\n  branch-per-change, PR-only landing.\n---\n\n" +
		marker + "\n\n# git-workflow\n\nBody line.\n"

	// bareSkill is the same skill as a REPO authors it after extraction: same frontmatter and body,
	// no marker. The two must read back to identical prose.
	bareSkill = "---\nname: git-workflow\ndescription: |-\n  branch-per-change, PR-only landing.\n---\n\n" +
		"# git-workflow\n\nBody line.\n"
)

// writeSkill lays out one skill directory, mirroring the on-disk contract.
func writeSkill(t *testing.T, tree, name, entry string, refs map[string]string) {
	t.Helper()
	dir := filepath.Join(tree, name)
	if err := os.MkdirAll(filepath.Join(dir, "references"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "SKILL.md"), []byte(entry), 0o644); err != nil {
		t.Fatal(err)
	}
	for stem, content := range refs {
		if err := os.WriteFile(filepath.Join(dir, "references", stem+".md"), []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

// TestReadSkillFile_ReadsTheCorpusShapeAndStripsItsMarker — the published shape is readable, and
// the DO-NOT-EDIT marker is not mistaken for prose.
func TestReadSkillFile_ReadsTheCorpusShapeAndStripsItsMarker(t *testing.T) {
	tree := t.TempDir()
	writeSkill(t, tree, "git-workflow", corpusSkill, nil)

	sf, err := ReadSkillFile(tree, "git-workflow")
	if err != nil {
		t.Fatalf("ReadSkillFile: %v", err)
	}
	if sf == nil {
		t.Fatal("ReadSkillFile returned nil for a file that exists")
	}
	if sf.Name != "git-workflow" || sf.Dir != "git-workflow" {
		t.Errorf("id = %q (dir %q), want git-workflow in both", sf.Name, sf.Dir)
	}
	if want := "branch-per-change, PR-only landing."; sf.Description != want {
		t.Errorf("description = %q, want %q", sf.Description, want)
	}
	if want := "# git-workflow\n\nBody line.\n"; sf.Content != want {
		t.Errorf("content = %q, want %q", sf.Content, want)
	}
	if strings.Contains(sf.Content, "GENERATED by") {
		t.Error("the generated marker leaked into Content — the emitter would publish it as prose")
	}
}

// TestReadSkillFile_ReadsTheBareAuthoredShape — the post-extraction shape reads identically: the
// marker is optional, the prose is not.
func TestReadSkillFile_ReadsTheBareAuthoredShape(t *testing.T) {
	tree := t.TempDir()
	writeSkill(t, tree, "git-workflow", bareSkill, nil)

	var corpus, bare *SkillFile
	var err error
	if corpus, err = ReadSkillFile(tree, "git-workflow"); err != nil {
		t.Fatalf("ReadSkillFile: %v", err)
	}
	bare, err = ReadSkillFile(tree, "git-workflow")
	if err != nil {
		t.Fatalf("ReadSkillFile: %v", err)
	}
	if corpus.Content != bare.Content || corpus.Description != bare.Description {
		t.Errorf("the corpus and bare shapes read back differently:\n%q vs %q", corpus.Content, bare.Content)
	}
	if !strings.HasPrefix(bare.Content, "# git-workflow") {
		t.Errorf("content = %q, want the body to start at the first markdown line", bare.Content)
	}
}

// TestReadSkillFile_BlockScalarKeepsATrailingNewline — the emitter picks `|` or `|-` from the
// authored value, so BOTH must read back exactly: a description ending in a newline keeps it.
func TestReadSkillFile_BlockScalarKeepsATrailingNewline(t *testing.T) {
	tree := t.TempDir()
	const kept = "---\nname: x\ndescription: |\n  first line\n  second line\n---\n\nbody\n"
	writeSkill(t, tree, "x", kept, nil)

	sf, err := ReadSkillFile(tree, "x")
	if err != nil {
		t.Fatalf("ReadSkillFile: %v", err)
	}
	if want := "first line\nsecond line\n"; sf.Description != want {
		t.Errorf("description = %q, want %q", sf.Description, want)
	}
}

// TestReadSkillFile_AbsentEntryIsNotAnError — (nil, nil): whether a skill MUST have a file is the
// caller's decision, and the generator is the caller that must be loud about it.
func TestReadSkillFile_AbsentEntryIsNotAnError(t *testing.T) {
	sf, err := ReadSkillFile(t.TempDir(), "not-here")
	if err != nil {
		t.Fatalf("a missing entry file is a normal state, got error: %v", err)
	}
	if sf != nil {
		t.Errorf("got %+v, want nil for an absent skill", sf)
	}
}

// TestReadSkillFile_RejectsANameThatDisagreesWithItsDirectory — the directory name IS the skill id
// the corpus publishes under, so a disagreeing frontmatter name would publish the wrong identity
// under the right path. It is an error, not a preference.
func TestReadSkillFile_RejectsANameThatDisagreesWithItsDirectory(t *testing.T) {
	tree := t.TempDir()
	writeSkill(t, tree, "git-workflow", "---\nname: something-else\n---\n\nbody\n", nil)

	_, err := ReadSkillFile(tree, "git-workflow")
	if err == nil {
		t.Fatal("a frontmatter name disagreeing with its directory was accepted")
	}
	for _, want := range []string{"something-else", "git-workflow"} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("error %q does not name %q — the reader must name both sides", err, want)
		}
	}
}

// TestReadSkillFile_RejectsMalformedFrontmatter — a broken fence must fail loudly: silently
// treating it as body would publish YAML as prose.
func TestReadSkillFile_RejectsMalformedFrontmatter(t *testing.T) {
	tree := t.TempDir()
	writeSkill(t, tree, "x", "---\nname: [unclosed\n---\n\nbody\n", nil)

	if _, err := ReadSkillFile(tree, "x"); err == nil {
		t.Error("malformed frontmatter was accepted")
	}
}

// TestReadSkillTree_ReadsEverySkillAndStemSortsItsReferences — one tree, every skill, references in
// a deterministic order, and a directory without an entry file ignored as "not a skill".
func TestReadSkillTree_ReadsEverySkillAndStemSortsItsReferences(t *testing.T) {
	tree := t.TempDir()
	writeSkill(t, tree, "git-workflow", corpusSkill, map[string]string{
		"zeta":  marker + "\n\nzeta body\n",
		"alpha": "alpha body\n",
	})
	writeSkill(t, tree, "strict-policy", "---\nname: strict-policy\ndescription: |-\n  R1-R5 operationalized.\n---\n\n# strict-policy\n\nBody.\n", nil)
	// A directory that is not a skill: no entry file.
	if err := os.MkdirAll(filepath.Join(tree, "not-a-skill"), 0o755); err != nil {
		t.Fatal(err)
	}

	skills, err := ReadSkillTree(tree)
	if err != nil {
		t.Fatalf("ReadSkillTree: %v", err)
	}
	if len(skills) != 2 {
		t.Fatalf("read %d skills, want 2 (a directory without SKILL.md is not a skill): %v", len(skills), keys(skills))
	}
	refs := skills["git-workflow"].References
	if len(refs) != 2 {
		t.Fatalf("read %d references, want 2", len(refs))
	}
	if refs[0].Stem != "alpha" || refs[1].Stem != "zeta" {
		t.Errorf("reference order = %q,%q, want alpha,zeta (stem-sorted)", refs[0].Stem, refs[1].Stem)
	}
	if want := "zeta body\n"; refs[1].Content != want {
		t.Errorf("reference content = %q, want %q (the marker is stripped here too)", refs[1].Content, want)
	}
}

// TestReadSkillTree_MissingTreeIsEmptyNotAnError — a repo that has not moved yet declares no tree;
// that is the normal pre-move state, not a failure.
func TestReadSkillTree_MissingTreeIsEmptyNotAnError(t *testing.T) {
	skills, err := ReadSkillTree(filepath.Join(t.TempDir(), "not-there"))
	if err != nil {
		t.Fatalf("a missing tree is a normal state, got error: %v", err)
	}
	if len(skills) != 0 {
		t.Errorf("got %d skills from an absent tree, want 0", len(skills))
	}
}

func keys(m map[string]*SkillFile) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	return out
}
