// skillfile_test.go — the `.agents/skills` reader's contract.
//
// Every fixture is byte-shaped the way the marketplace emitter writes it
// (candy/plugin-marketplace `emit_skills.go`: skillFrontmatter + the DO-NOT-EDIT marker +
// TrimSuffix(content, "\n") + "\n"), because the reader's whole job is to be that writer's exact
// inverse: read -> emit must land on the same bytes the corpus carries. The marker is spelled out
// here rather than imported so a change to the emitter's banner text fails THIS test loudly instead
// of silently changing what the reader strips.

const (
	marker = "<!-- GENERATED by `charly marketplace generate` — DO NOT EDIT. Edit the candy's skill:/hook:/marketplace: entities and regenerate. -->"

	// corpusSkill is a skill file as the published CORPUS carries it: frontmatter, marker, body.
	corpusSkill = "---\nname: git-workflow\ndescription: |-\n  branch-per-change, PR-only landing.\n---\n\n" +
		marker + "\n\n# git-workflow\n\nBody line.\n"

	// bareSkill is the same skill as a REPO authors it after extraction: same frontmatter and body,
	// no marker. The two must read back to identical prose.
	bareSkill = "---\nname: git-workflow\ndescription: |-\n  branch-per-change, PR-only landing.\n---\n\n" +
		"# git-workflow\n\nBody line.\n"
)

// writeSkill lays out one skill directory, mirroring the on-disk contract.
func writeSkill(t *testing.T, tree, name, entry string, refs map[string]string) {
	t.Helper()
	dir := filepath.Join(tree, name)
	if err := os.MkdirAll(filepath.Join(dir, "references"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "SKILL.md"), []byte(entry), 0o644); err != nil {
		t.Fatal(err)
	}
	for stem, content := range refs {
		if err := os.WriteFile(filepath.Join(dir, "references", stem+".md"), []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

// TestReadSkillFile_ReadsTheCorpusShapeAndStripsItsMarker — the published shape is readable, and
// the DO-NOT-EDIT marker is not mistaken for prose.
func TestReadSkillFile_ReadsTheCorpusShapeAndStripsItsMarker(t *testing.T) {
	tree := t.TempDir()
	writeSkill(t, tree, "git-workflow", corpusSkill, nil)

	sf, err := ReadSkillFile(tree, "git-workflow")
	if err != nil {
		t.Fatalf("ReadSkillFile: %v", err)
	}
	if sf == nil {
		t.Fatal("ReadSkillFile returned nil for a file that exists")
	}
	if sf.Name != "git-workflow" || sf.Dir != "git-workflow" {
		t.Errorf("id = %q (dir %q), want git-workflow in both", sf.Name, sf.Dir)
	}
	if want := "branch-per-change, PR-only landing."; sf.Description != want {
		t.Errorf("description = %q, want %q", sf.Description, want)
	}
	if want := "# git-workflow\n\nBody line.\n"; sf.Content != want {
		t.Errorf("content = %q, want %q", sf.Content, want)
	}
	if strings.Contains(sf.Content, "GENERATED by") {
		t.Error("the generated marker leaked into Content — the emitter would publish it as prose")
	}
}

// TestReadSkillFile_ReadsTheBareAuthoredShape — the post-extraction shape reads identically: the
// marker is optional, the prose is not.
func TestReadSkillFile_ReadsTheBareAuthoredShape(t *testing.T) {
	tree := t.TempDir()
	writeSkill(t, tree, "git-workflow", bareSkill, nil)

	var corpus, bare *SkillFile
	var err error
	if corpus, err = ReadSkillFile(tree, "git-workflow"); err != nil {
		t.Fatalf("ReadSkillFile: %v", err)
	}
	bare, err = ReadSkillFile(tree, "git-workflow")
	if err != nil {
		t.Fatalf("ReadSkillFile: %v", err)
	}
	if corpus.Content != bare.Content || corpus.Description != bare.Description {
		t.Errorf("the corpus and bare shapes read back differently:\n%q vs %q", corpus.Content, bare.Content)
	}
	if !strings.HasPrefix(bare.Content, "# git-workflow") {
		t.Errorf("content = %q, want the body to start at the first markdown line", bare.Content)
	}
}

// TestReadSkillFile_BlockScalarKeepsATrailingNewline — the emitter picks `|` or `|-` from the
