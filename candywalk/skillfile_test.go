// TestTheAgentTreeIsNotTheSkillTree — the LIVE defect this shape exists to fix, pinned. An
// `agent`-type node's body lands at <AgentsAgentsDir>/<name>.md; a body written into the SKILLS
// tree at `<tree>/<name>/SKILL.md` (which is what the pre-fix `extract` did, and what
// `pod-charly-automation#25` caught in the wild) is NOT an agent file. The two readers must not
// accept each other's layout, or a mis-placed body ships as an empty projection.
func TestTheAgentTreeIsNotTheSkillTree(t *testing.T) {
	// A body mis-placed into the skills tree, exactly as the pre-fix extract wrote it.
	body := strings.ReplaceAll(bareAgent, "pr-validator", "root-cause-analyzer")
	skillsTree := t.TempDir()
	writeSkill(t, skillsTree, "root-cause-analyzer", body, nil)
	if af, err := ReadAgentFile(skillsTree, "root-cause-analyzer"); err != nil || af != nil {
		t.Errorf("the agent reader accepted the SKILLS tree layout: %+v (err %v) — a mis-placed body must not read as an agent", af, err)
	}

	// And the reverse: an agent file is not a skill.
	agentsDir := t.TempDir()
	writeAgent(t, agentsDir, "root-cause-analyzer", body)
	if sf, err := ReadSkillFile(agentsDir, "root-cause-analyzer"); err != nil || sf != nil {
		t.Errorf("the skill reader accepted the AGENTS tree layout: %+v (err %v)", sf, err)
	}

	// The layout D8 rules: the two trees are SIBLINGS under the same parent.
	repo := t.TempDir()
	writeSkill(t, filepath.Join(repo, AgentsSkillsDir), "root-cause-analyzer", body, nil)
	writeAgent(t, filepath.Join(repo, AgentsAgentsDir), "root-cause-analyzer", body)

	sf, err := ReadSkillFile(filepath.Join(repo, AgentsSkillsDir), "root-cause-analyzer")
	if err != nil || sf == nil {
		t.Fatalf("the skill tree did not read: %+v (err %v)", sf, err)
	}
	af, err := ReadAgentFile(filepath.Join(repo, AgentsAgentsDir), "root-cause-analyzer")
	if err != nil || af == nil {
		t.Fatalf("the agent tree did not read: %+v (err %v)", af, err)
	}
}
