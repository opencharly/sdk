// skillfile.go — the authored FILE sources: the ONE reader of a `skill:` node's prose.
//
// A skill's body lives in the repository that owns it, not in its `skill:` entity:
//
//	<tree>/<name>/SKILL.md                 frontmatter (name + description) + the markdown body
//	<tree>/<name>/references/<stem>.md     no frontmatter, by contract
//
// where <tree> is the tree the owning candy's `skills:` list declares (default AgentsSkillsDir) and
// <name> is the skill id: the DIRECTORY name, which the frontmatter `name` must agree with. The
// entity keeps the routing (family/owner/triggers/category); the file keeps the prose. The version
// of record is the github ref that fetched the repo — the marketplace refs list's pin, or a
// consumer's `candy:` list — so nothing here fetches anything.
//
// An `agent`-type node is a SUB-AGENT DEFINITION, not a skill, so it has its own SHAPE at its own
// tree — ONE markdown file, with no entry directory and no split references:
//
//	<AgentsAgentsDir>/<name>.md            frontmatter (name + description) + the markdown body
//
// A candy's `skills:` list is a list of SKILL trees and does NOT govern that path, so a mixed repo
// — skills under a declared tree, agents under `.agents/agents` — is the legal shape, not a
// half-move. The two shapes differ ONLY in their paths: both go through the one parse
// (readAuthoredEntry), so a skill and an agent carrying the same bytes read back identically.
//
// The shape read here is BOTH the marketplace corpus's (banner included) and the bare shape a repo
// authors after extraction: the generator's DO-NOT-EDIT marker is stripped either way. That is what
// makes the relocation's round trip exact — `extract` writes the bare file, the corpus emitter
// re-writes it with the banner, and the two read back to the same Content.
//
// It lives in the shared kit, not in either generator, because BOTH need it
// (candy/plugin-marketplace and candy/plugin-docs) and R2 allows one implementation of one read.
// The docs projection's readSkill — fence split, two-key frontmatter, marker strip, stem-sorted
// references — is this function's prior art; it converges on this one.
const (
	// AgentsSkillsDir is the Agent-Skills standard location: what a candy's `skills:` list means
	// when it declares none.
	AgentsSkillsDir = ".agents/skills"

	// AgentsAgentsDir is the Agent-Skills standard location for sub-agent DEFINITIONS — the SIBLING
	// of AgentsSkillsDir, never a child of it. An `agent`-type node is authored at
	// <AgentsAgentsDir>/<name>.md: a sub-agent definition is not a skill, and a `skills:` list of
	// SKILL trees does not govern it (see the `skill` kind's own schema comment).
	AgentsAgentsDir = ".agents/agents"

	// skillEntryName is the one file name carrying a skill's frontmatter and body.
	skillEntryName = "SKILL.md"

	// skillReferencesDir is the one directory carrying a skill's split files.
	skillReferencesDir = "references"
)

// generatedHeaderRe matches the marketplace generator's DO-NOT-EDIT marker and the blank line that
// follows it, at the top of a body. It is a marker, never skill content.
var generatedHeaderRe = regexp.MustCompile(`(?m)^<!-- GENERATED by .*? -->\n\n`)

// SkillReferenceFile is one `references/<stem>.md` split file of a skill.
type SkillReferenceFile struct {
	Stem    string // the file stem: references/<stem>.md
	Content string // the file's markdown verbatim, marker stripped
}

// SkillFile is the prose half of a `skill:` entity, read from its file.
type SkillFile struct {
	// Name is the resolved skill id — the directory name, which the frontmatter `name` must agree
	// with when it states one.
	Name string
	// Dir is the directory the file was read from (equal to Name; kept separate so a caller that
	// reports a mismatch can name both sides).
	Dir string
	// Description is the frontmatter `description`: the Skill-tool dispatch keyword, and the public
	// subtitle when the corpus page is rendered.
	Description string
	// Content is the markdown body VERBATIM — marker stripped, and deliberately NOT trimmed. The
	// corpus emitter writes TrimSuffix(content, "\n") + "\n", so returning the body as authored is
	// exactly what makes read -> emit byte-identical.
	Content string
	// References are the skill's split files, stem-sorted so every consumer's output is deterministic.
	References []SkillReferenceFile
}

// AgentFile is the prose half of an `agent`-type skill node, read from its file.
//
// It is a SEPARATE type from SkillFile on purpose: the agent shape has no `references/` half and no
// entry DIRECTORY, so carrying SkillFile's `References`/`Dir` fields here would be two fields that
// can only ever be nil/empty — a shape pretending to be another shape.
type AgentFile struct {
	// Name is the resolved agent id — the `.md` file STEM, which the frontmatter `name` must agree
	// with when it states one.
	Name string
	// Description is the frontmatter `description`: the sub-agent's dispatch keyword.
	Description string
	// Content is the markdown body VERBATIM — marker stripped, and deliberately NOT trimmed, for the
	// same reason SkillFile.Content is: the corpus emitter writes TrimSuffix(content, "\n") + "\n".
	Content string
}

// authoredEntry is one authored markdown file's two prose halves, after the frontmatter fence has
// been split and the generator's marker stripped. It is the ONE parse both authored shapes share.
type authoredEntry struct {
	description string
	content     string
}

// readAuthoredEntry reads ONE authored markdown file and returns its prose. found is false — with a
// nil error — when the file does not exist, because whether a missing entry is legal is the
// caller's call.
//
// Everything else is an ERROR, because each case would otherwise publish the wrong prose under the
// right name: an unreadable file, malformed frontmatter, or a frontmatter `name` that disagrees with
// the name the file is filed under. Both shapes (`<tree>/<name>/SKILL.md` and
// `<AgentsAgentsDir>/<name>.md`) resolve to this one read, so they cannot drift apart.
func readAuthoredEntry(entry, name string) (authoredEntry, bool, error) {
	raw, err := os.ReadFile(entry)
	if err != nil {
		if os.IsNotExist(err) {
			return authoredEntry{}, false, nil
		}
		return authoredEntry{}, false, fmt.Errorf("read %s: %w", entry, err)
	}
	front, body := splitFrontmatter(string(raw))
	var fm struct {
		Name        string `yaml:"name"`
		Description string `yaml:"description"`
	}
	if front != "" {
		if err := yaml.Unmarshal([]byte(front), &fm); err != nil {
			return authoredEntry{}, false, fmt.Errorf("parse frontmatter of %s: %w", entry, err)
		}
	}
	if fm.Name != "" && fm.Name != name {
		return authoredEntry{}, false, fmt.Errorf("%s: frontmatter name %q disagrees with the name it is filed under %q — the file's own name IS the id", entry, fm.Name, name)
	}
	return authoredEntry{description: fm.Description, content: stripGeneratedHeader(body)}, true, nil
}

// ReadAgentFile reads ONE sub-agent definition: <agentsDir>/<name>.md.
//
// A missing file is (nil, nil), not an error — the same contract as ReadSkillFile's: whether an
// `agent` node MUST have a file is the caller's call, and the marketplace generator is the caller
// that hard-errors on a node with neither a file nor an in-line body, because publishing nothing
// there would silently drop a published sub-agent.
func ReadAgentFile(agentsDir, name string) (*AgentFile, error) {
	e, found, err := readAuthoredEntry(filepath.Join(agentsDir, name+".md"), name)
	if err != nil || !found {
		return nil, err
	}
	return &AgentFile{Name: name, Description: e.description, Content: e.content}, nil
}

// ReadSkillFile reads ONE skill's files: <treeDir>/<name>/SKILL.md, plus every
// <treeDir>/<name>/references/<stem>.md beside it.
//
// A missing entry file is (nil, nil), not an error — whether a skill MUST have one is the caller's
// call: the marketplace generator hard-errors when an entity carries neither a body nor a file,
// because publishing nothing there would silently drop a published skill. Everything else is an
// error, because each case would otherwise publish the wrong skill under the right name: an
// unreadable file, malformed frontmatter, or a frontmatter `name` that disagrees with its directory.
func ReadSkillFile(treeDir, name string) (*SkillFile, error) {
	dir := filepath.Join(treeDir, name)
	e, found, err := readAuthoredEntry(filepath.Join(dir, skillEntryName), name)
	if err != nil || !found {
		return nil, err
	}
	refs, err := readSkillReferences(filepath.Join(dir, skillReferencesDir))
	if err != nil {
		return nil, err
	}
	return &SkillFile{
		Name:        name,
		Dir:         name,
		Description: e.description,
		Content:     e.content,
		References:  refs,
	}, nil
}

// ReadSkillTree reads every skill one tree declares: every <treeDir>/<name>/SKILL.md, keyed by
// directory name. A directory without an entry file is not a skill and is skipped; a tree that does
// not exist at all is (empty, nil), because a repo that has not moved yet is a normal state and not
// an error.
func ReadSkillTree(treeDir string) (map[string]*SkillFile, error) {
	ents, err := os.ReadDir(treeDir)
	if err != nil {
		if os.IsNotExist(err) {
			return map[string]*SkillFile{}, nil
		}
		return nil, fmt.Errorf("read %s: %w", treeDir, err)
	}
	out := make(map[string]*SkillFile, len(ents))
	for _, e := range ents {
		if !e.IsDir() {
			continue
		}
		sf, err := ReadSkillFile(treeDir, e.Name())
		if err != nil {
			return nil, err
		}
		if sf == nil {
			continue
		}
		out[e.Name()] = sf
	}
	return out, nil
}

// readSkillReferences reads a skill's references/ directory, stem-sorted. A missing directory is
// (nil, nil): most skills carry no split files.
func readSkillReferences(dir string) ([]SkillReferenceFile, error) {
	ents, err := os.ReadDir(dir)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, fmt.Errorf("read %s: %w", dir, err)
	}
	out := make([]SkillReferenceFile, 0, len(ents))
	for _, e := range ents {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".md") {
			continue
		}
		raw, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			return nil, fmt.Errorf("read reference %s: %w", e.Name(), err)
		}
		out = append(out, SkillReferenceFile{
			Stem:    strings.TrimSuffix(e.Name(), ".md"),
			Content: stripGeneratedHeader(string(raw)),
		})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Stem < out[j].Stem })
	return out, nil
}

// splitFrontmatter separates a leading `---` YAML block from the markdown body. A file with no
// fence is all body: frontmatter is authored by the generator/extraction, never inferred.
//
// The frontmatter handed to the YAML parser KEEPS the newline that precedes the closing fence,
// because that newline is part of the block scalar: `description: |` (clip) keeps a final line
// break and `description: |-` (strip) removes it, and only a frontmatter that ends in a newline can
// tell those two apart. Cutting at the fence line instead would silently strip the `|` form's
// trailing newline, so a read -> emit round trip would rewrite the indicator and change the bytes.
// (The docs projection's earlier copy of this splitter cut it; L5 converges that caller here.)
func splitFrontmatter(s string) (front, body string) {
	if !strings.HasPrefix(s, "---\n") {
		return "", s
	}
	rest := s[len("---\n"):]
	end := strings.Index(rest, "\n---\n")
	if end < 0 {
		return "", s
	}
	return rest[:end+1], strings.TrimPrefix(rest[end+len("\n---\n"):], "\n")
}

// stripGeneratedHeader removes the generator's DO-NOT-EDIT marker (and its blank line) from the top
// of a body.
func stripGeneratedHeader(body string) string {
	return generatedHeaderRe.ReplaceAllString(body, "")
}
